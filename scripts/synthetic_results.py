fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), gridspec_kw={"wspace": 0.25})
pol = ["P1", "P2", "P3", "P4", "P5", "P6"]
track_sr = np.array([0.95, 0.93, 0.90, 0.88, 0.80, 0.70])
score_mean = np.array([0.60, 0.85, 0.70, 0.90, 0.75, 0.50])
