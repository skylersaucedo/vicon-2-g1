for p, sc, m1 in zip(pol, score_mean, s1):
    s = summarize(rollouts(sc + RNG.normal(0, 0.03))); s2.append(s["mean"])
    ax.plot(m1, s["mean"], "o", color=ORANGE, markeredgecolor="white", markersize=7)
    ax.annotate(p, (m1 + 0.008, s["mean"]), fontsize=8, color=INK2)
diff = np.abs(np.array(s1) - np.array(s2))
rater_disagree = RNG.binomial(int(0.25 * 270), 0.025) / int(0.25 * 270)
ax.annotate(f"mean |session 1 - session 2| = {diff.mean():.3f}" + NL + f"second-rater disagreement on 25% re-check = {rater_disagree:.3f}", (0.42, 0.93), fontsize=8, color=INK2, va="top")
finish(fig, "synthetic_e5_benchmark.png", "Six synthetic policies. Left: generating survival rates 0.95 to 0.70 and completion means 0.50 to 0.90 chosen so the rankings disagree. Right: session 2 regenerated with 0.03 drift; rater disagreement drawn at 2.5 percent, the TRI LBM re-check level.")
