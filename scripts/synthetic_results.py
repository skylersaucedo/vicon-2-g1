"""Synthetic results for the experiments proposed in potential-manuscript-ideas.md.

Every number produced here is generated from the stated assumptions with a fixed
random seed. Nothing is measured. The figures show what the data would look like
if the hypothesis held (left panel) and if it did not (right panel), so that the
analysis code and the decision rule are fixed before any capture session.

Usage: python scripts/synthetic_results.py images/
"""
import sys
import pathlib
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.stats import norm, spearmanr

OUT = pathlib.Path(sys.argv[1])
RNG = np.random.default_rng(0)
BLUE, ORANGE, AQUA, YELLOW = "#2a78d6", "#eb6834", "#1baf7a", "#eda100"
INK, INK2, GRID = "#1f1f1e", "#5e5d57", "#e4e3df"
N_ROLLOUTS = 45
N_MILESTONES = 5
NL = "\n"

plt.rcParams.update({"font.size": 9, "axes.edgecolor": INK2, "axes.labelcolor": INK,
                     "xtick.color": INK2, "ytick.color": INK2, "text.color": INK})


def wilson(k, n, z=norm.ppf(0.975)):
    p = k / n
    den = 1 + z**2 / n
    c = (p + z**2 / (2 * n)) / den
    h = z * np.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / den
    return c - h, c + h


def rollouts(mean_score, n=N_ROLLOUTS):
    """Milestone count per rollout. A rollout stops at the first failed milestone,
    so the count is the number of consecutive passes. Per-milestone pass
    probability q is chosen so the expected normalized score equals mean_score."""
    target = float(np.clip(mean_score, 0.02, 0.995))
    lo_q, hi_q = 0.0, 1.0
    for _ in range(60):  # bisection: E[score] = (q + q^2 + ... + q^5) / 5
        q = 0.5 * (lo_q + hi_q)
        if sum(q**i for i in range(1, N_MILESTONES + 1)) / N_MILESTONES < target:
            lo_q = q
        else:
            hi_q = q
    passes = RNG.random((n, N_MILESTONES)) < q
    first_fail = np.where(~passes.any(axis=1), N_MILESTONES, passes.argmin(axis=1))
    first_fail = np.where(passes.all(axis=1), N_MILESTONES, first_fail)
    return first_fail


def summarize(ms):
    score = ms / N_MILESTONES
    boot = RNG.choice(score, (10000, len(score))).mean(axis=1)
    k = int((ms == N_MILESTONES).sum())
    return dict(mean=score.mean(), lo=np.percentile(boot, 2.5), hi=np.percentile(boot, 97.5),
                k=k, n=len(ms), wlo=wilson(k, len(ms))[0], whi=wilson(k, len(ms))[1])


def style(ax, title, xlabel, ylabel, ylim=(-0.03, 1.05)):
    ax.set_title(title, loc="left", fontsize=9.5, fontweight="bold", color=INK)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.set_ylim(*ylim)
    ax.grid(True, axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


def errbar(ax, x, s, color, marker="o", label=None, dx=0.0, key=("mean", "lo", "hi")):
    m, lo, hi = (s[key[0]], s[key[1]], s[key[2]])
    ax.plot([x * 10**dx if ax.get_xscale() == "log" else x + dx] * 2, [lo, hi], color=color, linewidth=1.6, solid_capstyle="round")
    ax.plot(x * 10**dx if ax.get_xscale() == "log" else x + dx, m, marker=marker, markersize=7, color=color,
            markeredgecolor="white", markeredgewidth=1.2, linestyle="none", label=label)


def finish(fig, name, caption):
    fig.text(0.01, -0.02, "SYNTHETIC DATA generated by scripts/synthetic_results.py (seed 0). Not measured. " + caption,
             fontsize=7, color=INK2, ha="left", va="top", wrap=True)
    fig.savefig(OUT / name, dpi=170, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print("saved", OUT / name)


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return NL.join(out)


md = []

# E1 -------------------------------------------------------------------------
minutes = np.array([2.8, 5.6, 11.3, 22.5, 45.0])
beta, alpha = 0.60, -0.50
true_sup = 1 - beta * minutes**alpha
true_ref = np.full(5, 0.80)
fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), sharey=True, gridspec_kw={"wspace": 0.08})
rows = []
for ax, truth, title in ((axes[0], true_sup, "H1 holds: 1 - score = 0.60 x minutes^-0.50"),
                         (axes[1], true_ref, "H0 holds: flat at 0.80, knee below 2.8 min")):
    ax.set_xscale("log")
    style(ax, title, "Post-retargeting minutes (log scale)", "Normalized completion (milestones / 5)")
    ax.set_xlim(2, 70)
    means = []
    for m, t in zip(minutes, truth):
        s = summarize(rollouts(t))
        means.append(s["mean"])
        errbar(ax, m, s, BLUE)
        p = s["k"] / s["n"]
        ax.plot([m * 10**0.03] * 2, [s["wlo"], s["whi"]], color=ORANGE, linewidth=1.2, alpha=0.8)
        ax.plot(m * 10**0.03, p, marker="s", markersize=6, color=ORANGE, markeredgecolor="white", linestyle="none")
        rows.append((title.split(":")[0], m, f"{s['mean']:.2f} [{s['lo']:.2f}, {s['hi']:.2f}]", f"{s['k']}/{s['n']}", f"[{s['wlo']:.2f}, {s['whi']:.2f}]"))
    # two-parameter fit on the synthetic means
    y = 1 - np.array(means)
    A = np.vstack([np.log(minutes), np.ones(5)]).T
    a, b = np.linalg.lstsq(A, np.log(y), rcond=None)[0]
    xx = np.linspace(2.5, 60, 100)
    ax.plot(xx, 1 - np.exp(b) * xx**a, color=INK2, linewidth=1, linestyle=(0, (4, 3)))
    r = np.corrcoef(np.log(minutes), np.log(y))[0, 1]
    ax.annotate(f"fit alpha = {a:.2f}, Pearson r = {r:.2f}", (2.3, 0.25), fontsize=8, color=INK2)
    ax.axhline(0.8, color=GRID, linewidth=1)
axes[0].plot([], [], "o", color=BLUE, label="mean score, bootstrap 95% CI")
axes[0].plot([], [], "s", color=ORANGE, label="binary success k/45, Wilson 95% CI")
axes[0].legend(loc="lower right", frameon=False, fontsize=8)
finish(fig, "synthetic_e1_minutes_curve.png", "Each point is 45 simulated rollouts. Left: generated from a power law with alpha = -0.50. Right: generated from a constant 0.80.")
md.append(("E1", table(rows, ["Scenario", "Minutes", "Mean score [95% CI]", "Success k/n", "Wilson 95% CI"])))

