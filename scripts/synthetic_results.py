rows = []
s1 = []
for p, t, sc in zip(pol, track_sr, score_mean):
    s = summarize(rollouts(sc)); s1.append(s["mean"])
    k = int(RNG.binomial(45, t))
    ax.plot([k / 45] * 2, [s["lo"], s["hi"]], color=BLUE, linewidth=1.6)
    ax.plot(k / 45, s["mean"], "o", color=BLUE, markeredgecolor="white", markersize=7)
    ax.annotate(p, (k / 45 + 0.006, s["mean"]), fontsize=8, color=INK2)
    rows.append((p, f"{k}/45", f"{s['mean']:.2f} [{s['lo']:.2f}, {s['hi']:.2f}]"))
rho = spearmanr(track_sr, score_mean).correlation
ax.annotate(f"Spearman rho (survival vs score) = {rho:.2f}", (0.61, 0.08), fontsize=8, color=INK2)
ax = axes[1]
style(ax, "Test-retest after one week and rater agreement", "Session 1 mean score", "Session 2 mean score")
ax.set_xlim(0.4, 1.0); ax.set_ylim(0.4, 1.0)
ax.plot([0.4, 1.0], [0.4, 1.0], color=GRID, linewidth=1)
