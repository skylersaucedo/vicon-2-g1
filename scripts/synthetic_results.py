style(ax, "Milestone distribution per task and ablation", "Milestones reached per rollout", "Fraction of 45 rollouts", ylim=(0, 0.6))
conds = [("Sweep, tool randomized", 0.62, BLUE), ("Sweep, no tool randomization", 0.45, ORANGE),
         ("Dish rack, tool randomized", 0.66, AQUA), ("Dish rack, no tool randomization", 0.50, YELLOW)]
w = 0.2
rows = []
for j, (name, truth, color) in enumerate(conds):
    ms = rollouts(truth)
    hist = np.bincount(ms, minlength=6) / len(ms)
    ax.bar(np.arange(6) + (j - 1.5) * w, hist, width=w - 0.02, color=color, label=name)
    s = summarize(ms)
    rows.append((name, f"{s['mean']:.2f} [{s['lo']:.2f}, {s['hi']:.2f}]", f"{s['k']}/{s['n']}", " ".join(f"{int(h * 45)}" for h in hist)))
ax.set_xticks(range(6)); ax.set_xticklabels(["0", "1", "2", "3", "4", "5"])
ax.legend(loc="upper left", frameon=False, fontsize=7.5)
ax = axes[1]
style(ax, "Failure taxonomy of non-success rollouts (H1: tool contact dominates)", "Failure mode", "Fraction of failed rollouts", ylim=(0, 0.7))
modes = ["balance", "grasp", "tool contact", "timing"]
probs = {"Sweep": [0.10, 0.20, 0.55, 0.15], "Dish rack": [0.12, 0.35, 0.40, 0.13]}
